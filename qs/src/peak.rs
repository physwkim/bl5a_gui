//! The peak statistics SPEC's macros read after a scan (`CEN`, `pl_COM`,
//! `pl_xMAX`): a port of splot's `DataStatistics.py` 3.3 (`calc_peak`,
//! `calc_com`, `calc_hmx`, `calc_fwhm`), NaN behaviour included.

/// One scan's statistics.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Stats {
    /// `pl_xMAX`: x at the first maximum.
    pub xpk: f64,
    pub ymax: f64,
    /// `pl_COM`.
    pub com: f64,
    /// `CEN`: the midpoint of the half-maximum crossings.
    pub cen: f64,
    pub fwhm: f64,
}

/// numpy `max`: NaN if any element is.
fn max(y: &[f64]) -> f64 {
    y.iter().copied().fold(f64::NEG_INFINITY, |m, v| {
        if m.is_nan() || v.is_nan() {
            f64::NAN
        } else {
            m.max(v)
        }
    })
}

/// `_calc_index`: the first index of `v`, 0 for NaN.
fn index(v: f64, y: &[f64]) -> usize {
    if v.is_nan() {
        return 0;
    }
    y.iter().position(|&e| e == v).expect("the maximum is in y")
}

/// `calc_peak`: (x, y) of the first maximum, (0, 0) when it is NaN.
fn peak(x: &[f64], y: &[f64]) -> (f64, f64) {
    let m = max(y);
    if m.is_nan() {
        (0.0, 0.0)
    } else {
        (x[index(m, y)], m)
    }
}

/// `calc_com`; a NaN sum is truthy in Python.
fn com(x: &[f64], y: &[f64]) -> f64 {
    let sum: f64 = y.iter().sum();
    if sum != 0.0 {
        x.iter().zip(y).map(|(a, b)| a * b).sum::<f64>() / sum
    } else {
        0.0
    }
}

/// `calc_hmx`: the half-maximum crossing walking from the maximum in
/// `dir`, interpolated against the last point above half; the first
/// neighbour when half is never reached.
fn hmx(x: &[f64], y: &[f64], dir: isize) -> f64 {
    let npts = y.len() as isize;
    let mut y1 = max(y);
    let mut i = index(y1, y) as isize + dir;
    if i == npts {
        return x[x.len() - 1];
    }
    if i == -1 {
        return x[0];
    }
    let x0 = x[i as usize];
    let mut x1 = x0;
    let half = y1 / 2.0;
    loop {
        if (dir > 0 && i >= npts) || (dir < 0 && i < 0) {
            return x0;
        }
        let (xi, yi) = (x[i as usize], y[i as usize]);
        if yi <= half {
            let dy = y1 - yi;
            if dy != 0.0 {
                x1 -= (x1 - xi) * (y1 - half) / dy;
            }
            return x1;
        }
        x1 = xi;
        y1 = yi;
        i += dir;
    }
}

impl Stats {
    /// splot's statistics of `y` against `x`; `None` for an empty scan,
    /// on which splot raises.
    pub fn of(x: &[f64], y: &[f64]) -> Option<Self> {
        assert_eq!(x.len(), y.len(), "x and y differ in length");
        if y.is_empty() {
            return None;
        }
        let (xpk, ymax) = peak(x, y);
        let (lower, upper) = (hmx(x, y, -1), hmx(x, y, 1));
        let cen = if lower != xpk && upper != xpk {
            (upper + lower) / 2.0
        } else if upper == xpk {
            lower
        } else {
            upper
        };
        Some(Self {
            xpk,
            ymax,
            com: com(x, y),
            cen,
            fwhm: (upper - lower).abs(),
        })
    }
}

